package game.weapons;

/** Дробовик: 6 дробин, опустошает на ближней дистанции. */
public class Shotgun extends Weapon {

    public Shotgun() {
        super("Дробовик",
                17f,   // урон за дробину
                2.0f,  // множитель хедшота
                6,     // дробин за выстрел
                0.06f, // разброс
                0.95f, // пауза между выстрелами
                2.1f,  // перезарядка
                6,     // магазин
                48,    // макс. резерв
                24);   // начальный резерв
    }
}
